function assignArray<T>(target: T[], source: readonly T[]) {
  target.splice(0, target.length, ...source)
}

function assignFinder(target: typeof FINDER, source: typeof FINANCIAL_WELLBEING_DATA_EN.finder) {
  assignArray(target.steps as unknown as typeof source.steps[number][], source.steps as unknown as typeof source.steps[number][])
  assignArray(target.results as unknown as typeof source.results[number][], source.results as unknown as typeof source.results[number][])
}

function assignTabTags(target: Record<string, string[]>, source: Record<string, string[]>) {
  for (const key of Object.keys(target)) {
    delete target[key]
  }
  Object.assign(target, source)
}

export function syncFinancialWellbeingLocale(locale: FwLocale) {
  const data = FINANCIAL_WELLBEING_COPY[locale]
  assignArray(FW_NAV, data.fwNav)
  assignArray(FW_STATS, data.fwStats)
  assignArray(FEATURED_PATHS as unknown as typeof data.featuredPaths[number][], data.featuredPaths as unknown as typeof data.featuredPaths[number][])
  assignArray(COURSE_GROUPS as unknown as typeof data.courseGroups[number][], data.courseGroups as unknown as typeof data.courseGroups[number][])
  assignFinder(FINDER, data.finder)
  assignArray(LIBRARY_TABS as unknown as typeof data.libraryTabs[number][], data.libraryTabs as unknown as typeof data.libraryTabs[number][])
  assignTabTags(TAB_TAGS, data.tabTags)
  assignArray(FW_TESTIMONIALS as unknown as typeof data.testimonials[number][], data.testimonials as unknown as typeof data.testimonials[number][])
  assignArray(HOW_POINTS as unknown as typeof data.howPoints[number][], data.howPoints as unknown as typeof data.howPoints[number][])
}

